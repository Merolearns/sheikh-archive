"""Assemble v3/build/ from src/ and the v2 catalog, then verify it. Standard library only.

Two flavors from one shell:
  Preview/archive.html          single file, catalog inlined (what the launchers open)
  Preview/archive-hosted.html   multi-file, loads Preview/catalog.js?v=<version>
The DATA literal is copied byte for byte from v2, parsed back out of every output and
deep-compared, so the catalog can never drift.
"""

import hashlib
import json
import pathlib
import re
import shutil
import subprocess
import sys

V3 = pathlib.Path(__file__).resolve().parent
V2 = V3.parent / "build"
SRC = V3 / "src"
OUT = V3 / "build"
PV = OUT / "Preview"
LAUNCHERS = ("Start Archive - Windows.bat", "Start_Archive_-_macOS.command")

# Unfinished language that must never reach a shipped screen (brief, build action A).
PLACEHOLDERS = (
    "awaiting",
    "to be confirmed",
    "draft",
    "lorem",
    "coming soon",
    "tbd",
    "todo",
    "fixme",
    "بانتظار",
    "قيد التأكيد",
    "مسودة",
    "قريبا",
)


def data_literal(html):
    j = html.find("{", html.find("const DATA ="))
    obj, end = json.JSONDecoder().raw_decode(html[j:])
    return obj, html[j : j + end]


def shell(head_extra, data_script):
    css = (SRC / "app.css").read_text(encoding="utf-8")
    body = (SRC / "body.html").read_text(encoding="utf-8")
    app = (SRC / "app.js").read_text(encoding="utf-8")
    curation = json.dumps(
        json.loads((SRC / "content.json").read_text(encoding="utf-8")),
        ensure_ascii=False,
        separators=(",", ":"),
    )
    return (
        '<!DOCTYPE html>\n<html lang="ar" dir="rtl" data-theme="emerald">\n<head>\n'
        '<meta charset="UTF-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        '<meta name="color-scheme" content="dark light">\n'
        "<title>مكتبة فضيلة الشيخ الدكتور مصطفى كامل</title>\n"
        + head_extra
        + "<style>\n"
        + css
        + "</style>\n</head>\n<body>\n"
        + body
        + data_script
        + "<script>const CURATION = "
        + curation
        + ";</script>\n<script>\n"
        + app
        + "</script>\n</body>\n</html>\n"
    )


def ui_text(text):
    """The text a user can see: everything outside the catalog literal."""
    i = text.find("const DATA =")
    if i < 0:
        return text
    _, lit = data_literal(text)
    j = text.find(lit, i)
    return text[:i] + text[j + len(lit) :]


def main():
    v2_html = (V2 / "Preview/archive.html").read_text(encoding="utf-8")
    base, literal = data_literal(v2_html)
    version = hashlib.sha256(literal.encode()).hexdigest()[:12]

    if OUT.exists():
        shutil.rmtree(OUT)
    (PV / "docs").mkdir(parents=True)
    shutil.copytree(SRC / "assets", PV / "assets")
    shutil.copy2(V2 / "Preview/archive_server.py", PV / "archive_server.py")
    for f in LAUNCHERS:
        shutil.copy2(V2 / f, OUT / f)
    shutil.copy2(V3 / "docs/server-contract.md", PV / "docs/server-contract.md")

    catalog = (
        f"/* Archive catalog v3, version {version}. Generated by build.py; do not edit. */\n"
        f'const CATALOG_VERSION = "{version}";\n'
        "const DATA = " + literal + ";\n"
    )
    (PV / "catalog.js").write_text(catalog, encoding="utf-8")
    single = shell(
        "",
        f'<script>const CATALOG_VERSION = "{version}";\nconst DATA = '
        + literal
        + ";</script>\n",
    )
    hosted = shell(
        f'<meta name="catalog-version" content="{version}">\n',
        f'<script src="Preview/catalog.js?v={version}"></script>\n',
    )
    (PV / "archive.html").write_text(single, encoding="utf-8")
    (PV / "archive-hosted.html").write_text(hosted, encoding="utf-8")

    # ---- verify ----
    for name in ("archive.html", "catalog.js"):
        text = (PV / name).read_text(encoding="utf-8")
        built, lit = data_literal(text)
        assert lit == literal, f"{name}: DATA literal is not byte-identical to v2"
        assert built == base, f"{name}: DATA is not deep-equal to v2"
        assert text.count('"media":') == 3977, (
            f"{name}: {text.count(chr(34) + 'media' + chr(34) + ':')} media entries"
        )
        assert len(built["videos"]) == 3977 and len(built["playlists"]) == 71
        assert sum(len(p["items"]) for p in built["playlists"]) == 4320
    print(
        f"catalog byte-identical to v2 in archive.html and catalog.js (version {version}): 3977 media entries, 71 playlists, 4320 memberships"
    )

    ids = {v["id"] for v in base["videos"]}
    pls = {p["id"] for p in base["playlists"]}
    cur = json.loads((SRC / "content.json").read_text(encoding="utf-8"))
    assert set(cur["pillars"]) == pls, "pillar map must cover exactly the 71 playlists"
    assert len(cur["days"]) == 40 and all(
        i in ids for d in cur["days"] for i in d["ids"]
    )
    assert all(f["id"] in ids and f["pl"] in pls for f in cur["first"].values())
    print(
        "curation resolves: 71 playlists mapped, 40 days, 3 first lessons, all IDs in the catalog"
    )

    for name in ("archive.html", "archive-hosted.html"):
        ui = ui_text((PV / name).read_text(encoding="utf-8"))
        assert "—" not in ui, f"em dash in {name}"
        ext = re.findall(r"https?://[^\s\"'<>)]+", ui)
        assert not ext, f"external URL in {name}: {ext[:3]}"
        low = ui.lower()
        hits = [
            p
            for p in PLACEHOLDERS
            if re.search(r"(?<![\w-])" + re.escape(p) + r"(?![\w-])", low)
        ]
        assert not hits, f"placeholder language in {name}: {hits}"
    print("shell: no em dash, no external URL, no placeholder language (both flavors)")

    for f in LAUNCHERS:
        assert (OUT / f).read_bytes() == (V2 / f).read_bytes(), f"launcher differs: {f}"
    assert (PV / "archive_server.py").read_bytes() == (
        V2 / "Preview/archive_server.py"
    ).read_bytes()
    print("launchers and server byte-identical to v2")

    chk = OUT / ".check.js"
    chk.write_text((SRC / "app.js").read_text(encoding="utf-8"), encoding="utf-8")
    r = subprocess.run(["node", "--check", str(chk)], capture_output=True, text=True)
    chk.unlink()
    if r.returncode:
        sys.exit("JS syntax error:\n" + r.stderr)
    print("node --check app.js OK")
    for p in sorted(OUT.rglob("*")):
        if p.is_file():
            print(f"  {p.relative_to(OUT)}  {p.stat().st_size} bytes")


if __name__ == "__main__":
    main()
